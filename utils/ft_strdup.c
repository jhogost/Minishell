#include "minishell.h"

char	*ft_strdup(char *s)
{
	size_t	i;
	char	*copy;

	copy = malloc(sizeof(char) * ft_strlen(s) + 1);
	if (copy == NULL)
		return (NULL);
	i = 0;
	while (s[i] != '\0')
	{
		copy[i] = s[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
